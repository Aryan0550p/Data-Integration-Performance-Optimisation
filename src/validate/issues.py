"""
Formal Specification and Taxonomy of the 14 Integration Issues
"""
from dataclasses import dataclass
from enum import Enum
from typing import Optional, Dict, Any

class IntegrationIssueCode(str, Enum):
    ISSUE_01_ENCODING_CONFLICT = "ISSUE_01_ENCODING_CONFLICT"
    ISSUE_02_DATE_FORMAT_DISCREPANCY = "ISSUE_02_DATE_FORMAT_DISCREPANCY"
    ISSUE_03_SCHEMA_DRIFT_COLUMN_MAPPING = "ISSUE_03_SCHEMA_DRIFT_COLUMN_MAPPING"
    ISSUE_04_NUMERIC_CURRENCY_STRING = "ISSUE_04_NUMERIC_CURRENCY_STRING"
    ISSUE_05_PHONE_STANDARDIZATION = "ISSUE_05_PHONE_STANDARDIZATION"
    ISSUE_06_ORPHANED_FOREIGN_KEYS = "ISSUE_06_ORPHANED_FOREIGN_KEYS"
    ISSUE_07_DUPLICATE_TRANSACTIONS = "ISSUE_07_DUPLICATE_TRANSACTIONS"
    ISSUE_08_NULL_MANDATORY_FIELDS = "ISSUE_08_NULL_MANDATORY_FIELDS"
    ISSUE_09_CASE_INCONSISTENCY = "ISSUE_09_CASE_INCONSISTENCY"
    ISSUE_10_NESTED_STRUCTURAL_MUTATION = "ISSUE_10_NESTED_STRUCTURAL_MUTATION"
    ISSUE_11_BOOLEAN_DIVERGENCE = "ISSUE_11_BOOLEAN_DIVERGENCE"
    ISSUE_12_FLOAT_PRECISION_ROUNDING = "ISSUE_12_FLOAT_PRECISION_ROUNDING"
    ISSUE_13_CORRUPTED_POSTAL_CODES = "ISSUE_13_CORRUPTED_POSTAL_CODES"
    ISSUE_14_OUTLIER_RANGE_ANOMALIES = "ISSUE_14_OUTLIER_RANGE_ANOMALIES"

@dataclass
class IntegrationIssueRecord:
    issue_code: IntegrationIssueCode
    source_system: str
    record_identifier: str
    field_name: Optional[str]
    raw_value: Any
    resolved_value: Optional[Any]
    action_taken: str  # "TRANSFORMED", "QUARANTINED", "DEDUPLICATED", "PADDED"
    description: str
